-- Proof: SILVER_AP_INVOICES row counts by SOURCE_SYSTEM vs bronze sources
    WITH silver AS (
      SELECT SOURCE_SYSTEM,
             COUNT(*)                          AS SILVER_ROWS,
             COUNT(DISTINCT SOURCE_INVOICE_ID) AS DISTINCT_KEYS
      FROM COCO_WORKSHOP.PIPELINE_LAB.SILVER_AP_INVOICES
      GROUP BY SOURCE_SYSTEM
    ), bronze AS (
      SELECT 'SAP' AS SOURCE_SYSTEM, COUNT(*) AS BRONZE_ROWS FROM
  COCO_WORKSHOP.SOURCE_DATA.BRONZE_SAP_AP_INVOICES
      UNION ALL
      SELECT 'ORACLE', COUNT(*) FROM
  COCO_WORKSHOP.SOURCE_DATA.BRONZE_ORACLE_AP_INVOICES
    )
    SELECT COALESCE(b.SOURCE_SYSTEM, s.SOURCE_SYSTEM) AS SOURCE_SYSTEM,
           b.BRONZE_ROWS,
           COALESCE(s.SILVER_ROWS, 0)   AS SILVER_ROWS,
           COALESCE(s.DISTINCT_KEYS, 0) AS DISTINCT_KEYS,
           IFF(b.BRONZE_ROWS = s.SILVER_ROWS AND s.SILVER_ROWS = s.DISTINCT_KEYS,
  'PASS', 'FAIL') AS STATUS
    FROM bronze b
    FULL OUTER JOIN silver s ON s.SOURCE_SYSTEM = b.SOURCE_SYSTEM
    ORDER BY 1;